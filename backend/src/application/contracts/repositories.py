from typing import Any, Dict, List, Optional, Protocol


class ConversationsRepositoryLike(Protocol):
    def get_conversation_id_by_user(self, user_id: str) -> Optional[str]: ...

    def get_or_create_conversation_id(self, user_id: str) -> str: ...

    def touch_conversation(self, conversation_id: str) -> None: ...

    def get_summary(self, conversation_id: str) -> Optional[str]: ...

    def update_summary(self, conversation_id: str, summary: str) -> None: ...


class MessagesRepositoryLike(Protocol):
    def add_message(
        self,
        conversation_id: str,
        role: str,
        content: str,
        sources: Optional[List[Dict[str, Any]]] = None,
    ) -> None: ...

    def list_recent_messages(self, conversation_id: str, limit: int) -> List[Dict[str, Any]]: ...

    def count_messages(self, conversation_id: str) -> int: ...

    def clear_conversation(self, conversation_id: str) -> int: ...

    def invalidate_cache(self, conversation_id: str) -> None: ...
